def _empty_hint(text: str) -> None:
    """Render the italic placeholder used by empty sections."""
    ui.label(text).classes("text-sm text-gray-400 italic")


def _readonly_field(label: str, value: str) -> None:
    """Render a read-only label/value pair."""
    with ui.row().classes("w-full items-baseline gap-2"):
        ui.label(label).classes("w-28 shrink-0 text-sm text-gray-500")
        ui.label(value or "—").classes("flex-1 text-sm break-words")


def _safe_params(raw: str | None) -> dict:
    """Parse a JSON object, falling back to an empty dict."""
    if not raw:
        return {}
    try:
        parsed = json.loads(raw)
    except (TypeError, ValueError):
        return {}
    return parsed if isinstance(parsed, dict) else {}


def _relative_to_root(path: str, project_root: Path) -> str:
    """Convert an absolute path into a project-relative one."""
    import os

    return os.path.relpath(path, str(project_root))


def _reference_metadata(reference: dict) -> dict:
    """Parse the metadata_json of a reference, falling back to an empty dict."""
    return _safe_params(reference.get("metadata_json"))


def _photo_section(reference: dict) -> str:
    """The section title stored in a photo reference, or an empty string."""
    return (_reference_metadata(reference).get("section") or "").strip()


def _section_names(references: list[dict]) -> list[str]:
    """Distinct photo section titles of a memory, in order of first appearance."""
    names: list[str] = []
    for reference in references:
        if reference.get("ref_type") != "photo":
            continue
        section = _photo_section(reference)
        if section and section not in names:
            names.append(section)
    return names


def _next_section_name(references: list[dict]) -> str:
    """Return the next free 'Section <n>' title."""
    used = set()
    for name in _section_names(references):
        match = re.match(r"Section (\d+)$", name)
        if match:
            used.add(int(match.group(1)))
    n = 1
    while n in used:
        n += 1
    return f"Section {n}"


def _is_tool_output(reference: dict) -> bool:
    """True for figures generated by a tool run (they are shown in the Figures card)."""
    return reference.get("ref_type") == "figure" and "analysis_id" in _reference_metadata(reference)


def _group_references(references: list[dict]) -> dict[str, list[dict]]:
    """Group user-attached references by type keeping the canonical type order."""
    grouped: dict[str, list[dict]] = {}
    for reference in references:
        if _is_tool_output(reference):
            continue
        grouped.setdefault(reference.get("ref_type") or "other", []).append(reference)
    ordered = {kind: grouped[kind] for kind in REF_TYPES if kind in grouped}
    ordered.update({kind: items for kind, items in grouped.items() if kind not in REF_TYPES})
    return ordered


class SectionCard(ui.card):
    """Base class for a single memory detail section.

    Each card owns a refreshable body, so a mutation reloads only the cards that
    actually depend on the data that changed (see ``change_event`` / ``emit``).
    """

    #: Event emitted by ``notify_changed``; the owner maps it to the cards to reload.
    change_event: str = "memory"
    #: Whether the rendered body differs between view and edit mode.
    depends_on_editing: bool = True

    def __init__(self, *, key: str, memory: dict, project_root: Path,
                 editing: bool, conf: dict, height: int | None = None,
                 on_close: Callable[[str], None] | None = None,
                 on_changed: Callable[[str], None] | None = None) -> None:
        """Build the card shell and render its content."""
        super().__init__()
        self.key = key
        self.memory = memory or {}
        self.memory_id = self.memory.get("id")
        self.project_root = Path(project_root)
        self.editing = bool(editing)
        self.conf = conf or {}
        self.height = height
        self.on_close = on_close
        self.on_changed = on_changed

        self.classes("w-full p-0 gap-0 overflow-hidden")
        if height:
            self.style(f"min-height: {height}px")

        with self:
            self.header()
            with ui.card_section().classes("w-full p-4"):
                with ui.column().classes("w-full gap-3 items-stretch"):
                    self._render_body()

    @ui.refreshable_method
    def _render_body(self) -> None:
        """Render (or re-render) the card body in place."""
        self.content()

    def reload(self, memory: dict | None = None) -> None:
        """Refresh only this card, optionally with freshly loaded memory data."""
        if memory is not None:
            self.memory = memory
        self._render_body.refresh()

    def set_editing(self, editing: bool) -> None:
        """Switch the card between view and edit mode."""
        self.editing = bool(editing)

    def header(self) -> None:
        """Render icon, title and the fullscreen/close controls."""
        title, icon = SECTION_META.get(self.key, (self.key, "info"))
        with ui.row().classes("w-full items-center gap-2 px-4 py-2 bg-gray-100"):
            ui.icon(icon).classes("text-gray-600")
            ui.label(title).classes("text-base font-bold text-gray-800")
            ui.space()
            if self.conf.get("card_fullscreen", True):
                ui.icon("fullscreen").classes(
                    "cursor-pointer text-gray-500 hover:text-gray-900"
                ).on("click", lambda _, card=self: card.toggle_fullscreen()).tooltip("Toggle fullscreen")
            if self.on_close is not None:
                ui.icon("close").classes(
                    "cursor-pointer text-gray-500 hover:text-gray-900"
                ).on("click", lambda _, close=self.on_close, key=self.key: close(key)).tooltip("Hide section")

    def content(self) -> None:
        """Render the body of the card."""
        raise NotImplementedError

    def toggle_fullscreen(self) -> None:
        """Toggle the browser fullscreen mode for this card."""
        ui.run_javascript(f"""
            const el = document.querySelector(".q-card[id='c{self.id}']");
            if (!document.fullscreenElement) {{ el.requestFullscreen(); }}
            else {{ document.exitFullscreen(); }}
        """)

    def emit(self, event: str) -> None:
        """Ask the owner of the card to reload the cards affected by `event`."""
        if self.on_changed is not None:
            self.on_changed(event)

    def notify_changed(self) -> None:
        """Emit this card's default change event to the owner."""
        self.emit(self.change_event)

    def save_button(self, handler: Callable[[], None], label: str = "Save") -> None:
        """Render the primary action button used by the editable cards."""
        with ui.row().classes("w-full justify-end"):
            ui.button(label, icon="save", on_click=handler).props("dense color=primary")


class MetadataCard(SectionCard):
    """Title, date, substrate and process of a memory."""

    change_event = "metadata"

    def content(self) -> None:
        """Render the metadata block."""
        with ui.row().classes("w-full items-center gap-2"):
            ui.badge(self.memory.get("type") or "-").props("color=blue outline")
            if self.memory.get("subtype"):
                ui.badge(self.memory["subtype"]).props("color=gray outline")

        if not self.editing:
            _readonly_field("Title", self.memory.get("title", ""))
            _readonly_field("Date", self.memory.get("date", ""))
            _readonly_field("Substrate", self.memory.get("substrate", ""))
            _readonly_field("Process", self.memory.get("process", ""))
            return

        title_input = ui.input("Title", value=self.memory.get("title", "")).props("outlined dense").classes("w-full")
        date_input = ui.input("Date", value=self.memory.get("date", "")).props("outlined dense").classes("w-full")
        substrate_input = ui.input("Substrate", value=self.memory.get("substrate", "")).props("outlined dense").classes("w-full")
        process_input = ui.input("Process", value=self.memory.get("process", "")).props("outlined dense").classes("w-full")

        def save() -> None:
            db.update_memory(
                self.memory["id"],
                title=title_input.value or "",
                date=date_input.value or "",
                substrate=substrate_input.value or "",
                process=process_input.value or "",
            )
            ui.notify("Metadata saved", color="positive")
            self.notify_changed()

        self.save_button(save)


class DescriptionCard(SectionCard):
    """Free text description of a memory."""

    change_event = "description"

    def content(self) -> None:
        """Render the description block."""
        description = self.memory.get("description") or ""

        if not self.editing:
            if description:
                ui.label(description).classes("w-full text-sm whitespace-pre-wrap")
            else:
                _empty_hint("No description")
            return

        area = ui.textarea(value=description).props("outlined dense autogrow").classes("w-full")

        def save() -> None:
            db.update_memory(self.memory["id"], description=area.value or "")
            ui.notify("Description saved", color="positive")
            self.notify_changed()

        self.save_button(save)


class FieldsCard(SectionCard):
    """All the fields of a memory, as a table or as editable rows."""

    change_event = "fields"

    def fields(self) -> list[dict]:
        """Return every field of the memory."""
        return list(self.memory.get("fields", []))

    def content(self) -> None:
        """Render the fields as a table or as editable rows."""
        fields = self.fields()

        if not self.editing:
            if not fields:
                _empty_hint("No fields")
                return
            ui.table(
                columns=FIELD_COLUMNS,
                rows=[
                    {
                        "id": field.get("id"),
                        "field_name": field.get("field_name", ""),
                        "field_value": field.get("field_value", ""),
                    }
                    for field in fields
                ],
            ).classes("w-full").props("dense flat hide-pagination")
            return

        for field in fields:
            with ui.row().classes("w-full items-center gap-2"):
                name_input = ui.input(value=field.get("field_name", "")).props("dense outlined").classes("flex-1")
                value_input = ui.input(value=field.get("field_value", "")).props("dense outlined").classes("flex-1")
                ui.button(icon="delete", on_click=lambda _, f=field: self.delete_field(f)).props(
                    "flat dense color=negative size=sm"
                )

                def save_field(e=None, f=field, name_w=name_input, value_w=value_input) -> None:
                    db.update_field(f["id"], field_name=name_w.value or "", field_value=value_w.value or "")

                name_input.on("blur", save_field)
                value_input.on("blur", save_field)
                name_input.on("keydown.enter", save_field)
                value_input.on("keydown.enter", save_field)

        with ui.row().classes("w-full items-center gap-2"):
            new_name = ui.input("Name").props("dense outlined").classes("flex-1")
            new_value = ui.input("Value").props("dense outlined").classes("flex-1")
            ui.button("Add", icon="add", on_click=lambda: self.add_field(new_name, new_value)).props("dense color=primary")

    def delete_field(self, field: dict) -> None:
        """Remove a field and refresh the view."""
        db.delete_field(field["id"])
        ui.notify("Field deleted", color="positive")
        self.notify_changed()

    def add_field(self, name_input: ui.input, value_input: ui.input) -> None:
        """Create a new field from the add row."""
        name = (name_input.value or "").strip()
        if not name:
            ui.notify("A field name is required", color="negative")
            return
        db.add_field(self.memory["id"], name, value_input.value or "")
        name_input.set_value("")
        value_input.set_value("")
        ui.notify("Field added", color="positive")
        self.notify_changed()


class ReferencesCard(SectionCard):
    """Attached files grouped by type, with the tools that can run on them."""

    change_event = "references"

    def _runs_changed(self) -> None:
        """Signal that tool runs changed (affects References, Analysis, Figures)."""
        self.emit("runs")

    def content(self) -> None:
        """Render the reference groups, the tools applied to each and the add-files row."""
        grouped = _group_references(self.memory.get("references", []))
        runs_by_ref = self._runs_by_ref()

        if not grouped:
            _empty_hint("No references")
        for ref_type, references in grouped.items():
            with ui.expansion(f"{ref_type} ({len(references)})", icon=REF_ICONS.get(ref_type, "insert_drive_file")).classes("w-full"):
                for reference in references:
                    path = reference.get("ref_path", "")
                    with ui.column().classes("w-full gap-1"):
                        with ui.row().classes("w-full items-center gap-2"):
                            ui.badge(reference.get("ref_type", "")).props("outline color=gray")
                            ui.label(path).classes("flex-1 truncate font-mono text-sm").tooltip(path)
                            if reference.get("ref_type") == "hdf5":
                                ui.button("Apply tool", icon="play_arrow", on_click=lambda _, p=path: self.apply_tool(p)).props(
                                    "dense flat color=primary size=sm"
                                )
                            if self.editing:
                                ui.button(icon="delete", on_click=lambda _, r=reference: self.delete_reference(r)).props(
                                    "flat dense color=negative size=sm"
                                )
                        for run in runs_by_ref.get(path, []):
                            self._render_run_row(run)

        if not self.editing:
            return

        with ui.row().classes("w-full items-end gap-2"):
            ref_type_select = ui.select(list(REF_TYPES), value="csv", label="Type").props("outlined dense").classes("w-32")

            section_select = ui.select(
                _section_names(self.memory.get("references", [])),
                label="Section",
                with_input=True,
                new_value_mode="add-unique",
            ).props("outlined dense clearable").classes("w-44")

            ui.button("Add Files", icon="attach_file", on_click=lambda: self.pick_files(ref_type_select, section_select)).props(
                "dense color=primary"
            )

        def _toggle_section(event=None) -> None:
            value = event.value if event is not None else ref_type_select.value
            section_select.set_visibility(value == "photo")

        ref_type_select.on_value_change(_toggle_section)
        _toggle_section()

    def _runs_by_ref(self) -> dict[str, list[dict]]:
        """Group the memory's tool runs by the source reference they used."""
        grouped: dict[str, list[dict]] = {}
        for run in self.memory.get("tool_runs", []):
            grouped.setdefault(run.get("ref_path", ""), []).append(run)
        return grouped

    def _render_run_row(self, run: dict) -> None:
        """One line showing an applied tool, with re-run and remove buttons."""
        with ui.row().classes("w-full items-center gap-2 pl-6"):
            ui.icon("insights").classes("text-gray-400 text-sm")
            ui.label(summarize_run(run)).classes("flex-1 text-xs text-gray-600")
            ui.button(icon="replay", on_click=lambda _, r=run: self._rerun(r)).props(
                "flat dense color=primary size=sm"
            ).tooltip("Re-run with the same parameters")
            ui.button(icon="delete", on_click=lambda _, r=run: _confirm_remove_run(r, self._runs_changed)).props(
                "flat dense color=negative size=sm"
            ).tooltip("Remove this tool and everything it produced")

    def _rerun(self, run: dict) -> None:
        """Re-apply an existing tool run with its stored parameters."""
        try:
            new_id = rerun_tool_run(run["id"])
        except Exception as exc:
            ui.notify(f"Re-run failed: {exc}", color="negative", multi_line=True, timeout=8000)
            return
        if new_id is None:
            ui.notify("That run was already gone", color="warning")
        else:
            ui.notify(f"Re-ran {run.get('tool_name', 'tool')}", color="positive")
        self._runs_changed()

    def apply_tool(self, ref_path: str) -> None:
        """Open the Apply tool dialog for an HDF5 reference."""
        show_tool_dialog(self.memory["id"], ref_path, self.project_root, on_done=self._runs_changed)

    def delete_reference(self, reference: dict) -> None:
        """Remove a reference and refresh the view."""
        db.delete_reference(reference["id"])
        ui.notify("Reference deleted", color="positive")
        self.notify_changed()

    async def pick_files(self, ref_type_select: ui.select, section_select: ui.select) -> None:
        """Pick files and attach them with the selected reference type."""
        ref_type = ref_type_select.value or "csv"
        paths = await pick_file(
            directory=str(self.project_root),
            multiple=True,
            extensions=REF_EXTENSIONS.get(ref_type, ()),
        )
        if not paths:
            return

        metadata = None
        if ref_type == "photo":
            title = (section_select.value or "").strip() or _next_section_name(self.memory.get("references", []))
            metadata = {"section": title}

        for path in paths:
            db.add_reference(self.memory["id"], ref_type, _relative_to_root(path, self.project_root), metadata)
        ui.notify(f"Added {len(paths)} reference(s)", color="positive")
        self.notify_changed()


class AnalysisCard(SectionCard):
    """Applied tools: parameters, summary and data tables of each run."""

    depends_on_editing = False

    def content(self) -> None:
        """Render one expansion per applied tool."""
        runs = self.memory.get("tool_runs", [])
        if not runs:
            _empty_hint("No tools applied yet. Use Apply tool on an HDF5 reference in References.")
            return

        for run in runs:
            created_at = (run.get("created_at") or "")[:10]
            with ui.expansion(f"{run.get('tool_name', '?')} ({created_at})").classes("w-full"):
                if run.get("description"):
                    ui.label(run["description"]).classes("text-sm text-gray-700")
                ui.label(f"Source: {run.get('ref_path', '')}").classes("font-mono text-xs text-gray-500")
                _render_block("Parameters", _safe_params(run.get("params_json")))
                _render_block("Summary", _safe_params(run.get("summary_json")))
                for item in run.get("items", []):
                    if item.get("kind") == "table":
                        _render_table_item(item)


def _render_table_item(item: dict) -> None:
    """Render one table produced by a run."""
    content = _safe_params(item.get("content_json"))
    records = content.get("records", []) if isinstance(content, dict) else []
    label = item.get("label") or "table"
    with ui.expansion(f"{label} ({len(records)} rows)").classes("w-full mt-1"):
        if records:
            columns = [{"name": key, "label": key, "field": key} for key in records[0].keys()]
            ui.table(columns=columns, rows=records).classes("w-full").props("dense flat")
        else:
            _empty_hint("Empty table")


def _render_block(title: str, values: dict) -> None:
    """Render a titled key/value block, expanding nested dicts one level."""
    if not values:
        return
    ui.label(title).classes("text-sm font-medium mt-1")
    for name, value in values.items():
        if isinstance(value, dict):
            ui.label(f"{name}:").classes("pl-4 text-sm text-gray-700")
            for sub_name, sub_value in value.items():
                ui.label(f"{sub_name}: {_format(sub_value)}").classes("pl-8 text-sm text-gray-600")
        else:
            ui.label(f"{name}: {_format(value)}").classes("pl-4 text-sm text-gray-700")


def _format(value) -> str:
    if isinstance(value, float):
        return f"{value:.4g}"
    if isinstance(value, list) and len(value) > 8:
        return f"[{len(value)} items]"
    return str(value)


class FiguresCard(SectionCard):
    """Interactive figures produced by the applied tools."""

    depends_on_editing = False

    def content(self) -> None:
        """Render the figures of every applied tool, plus legacy CSV charts."""
        runs = [
            run for run in self.memory.get("tool_runs", [])
            if any(item.get("kind") == "figure" for item in run.get("items", []))
        ]
        csv_refs = [r for r in self.memory.get("references", []) if r.get("ref_type") == "csv"]

        if not runs and not csv_refs:
            _empty_hint("No figures yet. Apply a tool to an HDF5 reference in References.")
            return

        for run in runs:
            self._render_run(run)

        for reference in csv_refs:
            create_csv_viewer(self.project_root / reference.get("ref_path", ""))

    def _max_height(self) -> int | None:
        return (self.conf.get("figures") or {}).get("max_height")

    def _render_run(self, run: dict) -> None:
        """Show one applied tool: all its figures stacked vertically."""
        name = run.get("tool_name", "tool")
        date = (run.get("created_at") or "")[:10]
        figures = [item for item in run.get("items", []) if item.get("kind") == "figure"]

        with ui.expansion(f"{name} · {date} ({len(figures)} figures)", icon="insights", value=True).classes("w-full"):
            with ui.column().classes("w-full gap-4"):
                for item in figures:
                    create_plotly_viewer(_safe_params(item.get("content_json")), max_height=self._max_height())


def _confirm_remove_run(run: dict, on_done: Callable[[], None]) -> None:
    """Ask for confirmation, then remove the tool run and everything it produced."""
    with ui.dialog() as dlg, ui.card().classes("w-96"):
        ui.label(f"Remove {run.get('tool_name', 'tool')}?").classes("text-lg font-bold")
        ui.label(summarize_run(run)).classes("text-sm text-gray-600")
        ui.label("This deletes the run and all the figures and data it produced.").classes(
            "text-xs text-gray-500"
        )
        with ui.row().classes("w-full justify-end gap-2 mt-2"):
            ui.button("Cancel", on_click=dlg.close).props("flat")

            def do_remove() -> None:
                dlg.close()
                removed = remove_tool_run(run["id"])
                if removed is None:
                    ui.notify("That run was already gone", color="warning")
                else:
                    ui.notify(f"Removed — {summarize_run(removed)}", color="positive")
                on_done()

            ui.button("Remove", icon="delete", on_click=do_remove).props("color=negative")

    dlg.open()


class PhotosCard(SectionCard):
    """Photo gallery grouped by titled, collapsible sections."""

    depends_on_editing = False

    def content(self) -> None:
        """Render photos grouped by their section, each under a titled separator."""
        photo_refs = [r for r in self.memory.get("references", []) if r.get("ref_type") == "photo"]
        if not photo_refs:
            _empty_hint("No photo references")
            return

        photos_conf = self.conf.get("photos") or {}
        columns = photos_conf.get("columns", 4) or 4
        thumb_size = photos_conf.get("thumb_size", 160) or 160

        groups: dict[str, list[dict]] = {}
        for reference in photo_refs:
            section = (_reference_metadata(reference).get("section") or "").strip() or DEFAULT_PHOTO_SECTION
            groups.setdefault(section, []).append(reference)

        for title, refs in groups.items():
            ui.separator().classes("mt-2")
            with ui.expansion(f"{title} ({len(refs)})", value=True, icon="photo_library").classes("w-full"):
                with ui.grid(columns=columns).classes("w-full gap-2 justify-items-center"):
                    for reference in refs:
                        create_photo_viewer(
                            self.project_root / reference.get("ref_path", ""), thumb_size
                        )


